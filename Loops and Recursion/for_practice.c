# include <stdio.h>

int main(){
    int i = 1024;
    for(;i /*will be true if i !=0*/; i>>=1)
    {
        printf("Hello Python %d\n", i);
        /*
            1024 = 100 0000 0000
            1024>>1 = 010 0000 0000
            512>>1 = 001 0000 0000
            256>>1 = 256/2**1 = 128
            128>>1 = 64
            64 >> 1 = 32
            32 >> 1 = 16
            16 >> 1 = 8
            8 >> 1 = 4
            2 >> 1 = 1
            1 >> 1 = 0
        */
    }
    
    return 0;
}